const assert=require('node:assert/strict'),C=require('./collage-core.js');
const job={id:'job',records:[{id:'001'},{id:'002'}]};
const prefix='{"jobId":"job","items":[';
const row={id:'001',translated:'引用 " と } { と \\\\ と改行\n 日本語'};
const first=prefix+JSON.stringify(row);
assert.equal(C.streamResponse(prefix,job),null);
assert.equal(C.streamResponse(first.slice(0,-1),job),null);
assert.deepEqual(JSON.parse(C.streamResponse(first,job)).items,[row]);
assert.deepEqual(JSON.parse(C.streamResponse(first+',{"id":"002","translated":"途中',job)).items,[row]);
assert.equal(C.streamResponse(first.replace('"job"','"other"'),job),null);
assert.equal(C.streamResponse('説明 '+first,job),null);
assert.equal(C.streamResponse(first+','+JSON.stringify(row),job),null);
assert.equal(C.streamResponse(prefix+'{"id":"unknown","translated":"訳"}',job),null);
assert.equal(C.streamResponse(prefix+'{"id":"001","translated":""}',job),null);
const skipped=C.streamResponse(prefix+'{"id":"001","skip":true}',job);
assert.equal(C.parsePartial(skipped,job).blocks.length,0);
assert.equal(C.streamResponse('x'.repeat(1000001),job),null);
assert.ok(C.streamResponse(String.fromCharCode(96).repeat(3)+'json\n'+first,job));
for(let i=0;i<JSON.stringify(row).length-1;i++)assert.equal(C.streamResponse(prefix+JSON.stringify(row).slice(0,i),job),null);
console.log('PASS: streamed objects, escaped strings, truncation, current job, invalid IDs, duplicate rejection, skip and code fences');
